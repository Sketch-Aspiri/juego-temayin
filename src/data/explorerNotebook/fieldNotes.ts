type FieldNote = readonly [levelId: string, factIndex: 0 | 1 | 2, id: string, title: string, toh: string];
const PLACES: Readonly<Record<string, string>> = {
  '2-4': 'Petenes', '3-4': 'Teya', '5-4': 'Xcaret', '5-5': 'Puerto Aventuras', '5-6': 'Akumal', '7-4': 'Calakmul',
};

/** Reutiliza datos y referencias ya revisados; cada título identifica el sitio real del apunte. */
function fieldNote([levelId, factIndex, id, title, toh]: FieldNote): NotebookEntry {
  const station = STATION_INFO[levelId];
  const fact = station.facts[factIndex];
  const context = station.relation === 'fiction'
    ? 'Este escenario del juego es ficticio. El dato siguiente corresponde al patrimonio real de la región. '
    : '';
  return {
    id, levelId, place: PLACES[levelId] ?? station.location.split(' · ')[0], title, category: fact.category,
    format: 'field-note', text: context + fact.text, toh,
    sources: [{ label: `INAH · ${fact.source.section}, ${pageLabel(fact.source)}`, url: guideUrl(fact.source) }],
  };
}

